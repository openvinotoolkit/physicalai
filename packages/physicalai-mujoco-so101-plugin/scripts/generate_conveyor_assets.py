CYLINDER_SEGMENTS = 32
CYLINDER_SKIN_REPEATS = 3  # crack skin repeats around the cylinder, so tiles stay about square
BELT_HALF = (0.04, 0.41, 0.005)  # keep in sync with the conveyor_belt geom in scene.xml
BELT_TILE = 0.02  # keep in sync with conveyor.BELT_TILE

# Bin labels: a white plate on each bin floor, text facing the standard overview camera.
LABEL_HALF = (0.02, 0.043, 0.0004)  # x (text height), y (text width), z; metres
LABEL_PX = (300, 140)  # width, height; same aspect as the plate

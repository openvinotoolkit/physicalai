"""Generate the conveyor_sort textures, UV-mapped visual meshes and item pool XML.

Every textured surface is a mesh with UV coordinates and a 2D texture. That is
the only textured case both MuJoCo's renderer (the camera streams) and the
mjviser browser viewer draw; mjviser renders primitives with a flat color and
reduces cube maps to one color per face.
"""  # noqa: INP001

